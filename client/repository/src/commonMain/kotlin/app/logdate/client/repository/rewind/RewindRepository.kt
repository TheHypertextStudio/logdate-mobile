package app.logdate.client.repository.rewind

import app.logdate.shared.model.Rewind
import kotlinx.coroutines.flow.Flow
import kotlin.time.Instant
import kotlin.uuid.Uuid

/**
 * A repository for managing Rewind data.
 */
interface RewindRepository {
    /**
     * Retrieves all Rewinds that have been generated.
     */
    fun getAllRewinds(): Flow<List<Rewind>>

    /**
     * Retrieves a Rewind by its unique identifier.
     */
    fun getRewind(uid: Uuid): Flow<Rewind>

    /**
     * Retrieves a Rewind for a given time period.
     *
     * @param start The start of the time period.
     * @param end The end of the time period.
     * @return The Rewind for the given time period.
     */
    fun getRewindBetween(
        start: Instant,
        end: Instant,
    ): Flow<Rewind?>

    /**
     * Checks if a Rewind is available for the given time period.
     *
     * If there is no content available for the given time period, the Rewind is not available.
     */
    suspend fun isRewindAvailable(
        start: Instant,
        end: Instant,
    ): Boolean

    /**
     * Creates a new Rewind for the given time period.
     *
     * This will use all available user data to create the Rewind, including:
     * - Journal entry text content
     * - Location history
     *
     * @param start The start of the time period.
     * @param end The end of the time period.
     * @return The created Rewind.
     * @deprecated Use GenerateBasicRewindUseCase instead
     */
    @Deprecated("Use GenerateBasicRewindUseCase instead")
    suspend fun createRewind(
        start: Instant,
        end: Instant,
    ): Rewind

    /**
     * Saves a rewind to the repository.
     *
     * @param rewind The rewind to save
     */
    suspend fun saveRewind(rewind: Rewind)

    /** Atomically updates one Rewind and its panels, keeping its UID and attached replies. */
    suspend fun replaceRewind(
        existingUid: Uuid,
        replacement: Rewind,
    ): Unit = throw UnsupportedOperationException("Atomic Rewind replacement is unavailable")

    /**
     * Removes a rewind and all of its content from the repository.
     *
     * Cascade-delete on the underlying foreign keys takes care of the rewind's text,
     * image, and video rows along with any prompt replies.
     *
     * @param uid The unique identifier of the rewind to delete.
     */
    suspend fun deleteRewind(uid: Uuid)

    /**
     * Retrieves all rewinds whose entire date range falls within [start]..[end],
     * ordered chronologically. Used by the annual rewind pipeline to collect the
     * weekly and milestone rewinds that feed the year narrative.
     */
    fun getRewindsInRange(
        start: Instant,
        end: Instant,
    ): Flow<List<Rewind>>

    /**
     * Records that the user has opened this rewind. On the first call for a given
     * rewind, sets the viewed flag and records the timestamp. On subsequent calls,
     * increments the view count.
     */
    suspend fun markAsViewed(uid: Uuid)

    /**
     * Stamps a rewind as a milestone-detected rewind by writing [signal] into the
     * first slot of its `metadata.milestones` list.
     *
     * Doesn't touch the panel content rows — the rewind body has already been
     * generated by the normal pipeline before this is called. The overview screen
     * reads the signal back at display time and picks a distinct card treatment.
     *
     * @param uid Identifier of the rewind to tag.
     * @param signal Encoded `MILESTONE_KIND:summary` string — see
     *   [toMetadataSignal].
     */
    suspend fun tagAsMilestone(
        uid: Uuid,
        signal: String,
    )
}
